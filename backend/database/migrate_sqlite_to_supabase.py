"""
==============================================================================
VAYU — SQLite to Supabase PostgreSQL Safe Migration Tool
==============================================================================
Safely migrates the canonical SQLite database (cyclone_intel.db) to Supabase
PostgreSQL while preserving IDs, foreign keys, timestamps, and schema integrity.

Features:
- Idempotent and safe to re-run (uses ON CONFLICT DO NOTHING).
- Strictly preserves existing primary-key IDs via GENERATED BY DEFAULT AS IDENTITY.
- Preserves observation timestamp strings and converts system timestamps to TIMESTAMPTZ.
- Bridges the disaster_alerts column mismatch safely without modifying source SQLite.
- Synchronizes identity sequences correctly for both empty and populated tables.
- Read-only source access: NEVER modifies the SQLite database.
- Validates row counts and foreign-key integrity post-migration.

Usage:
  # Standard migration using DATABASE_URL environment variable:
  python backend/database/migrate_sqlite_to_supabase.py

  # With explicit database URL:
  python backend/database/migrate_sqlite_to_supabase.py --database-url "postgresql://..."

  # Verification-only mode (checks target state without inserting):
  python backend/database/migrate_sqlite_to_supabase.py --verify-only

  # Dry-run mode (reads and validates SQLite source without writing to Postgres):
  python backend/database/migrate_sqlite_to_supabase.py --dry-run
==============================================================================
"""

