def test_timestamp_parser_formats():
    """Verify safe parsing of timestamps across varied SQLite source formats."""
    # Standard ISO format
    dt1 = parse_timestamp_safely("2026-09-20 15:03:53")
    assert dt1 is not None
    assert dt1.year == 2026 and dt1.month == 9 and dt1.day == 20
    assert dt1.tzinfo == datetime.timezone.utc

    # ISO with Z
    dt2 = parse_timestamp_safely("2026-09-20T15:26:50Z")
    assert dt2 is not None
    assert dt2.minute == 26 and dt2.second == 50

    # IST string
    dt3 = parse_timestamp_safely("2026-09-02 12:00:00 IST")
    assert dt3 is not None
    assert dt3.hour == 12

    # None / empty preservation
    assert parse_timestamp_safely(None) is None
    assert parse_timestamp_safely("") is None


