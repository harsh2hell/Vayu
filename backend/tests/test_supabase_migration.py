def test_schema_file_exists():
    """Verify that backend/database/supabase_schema.sql exists and is non-empty."""
    assert SCHEMA_FILE.exists(), f"Schema file not found at {SCHEMA_FILE}"
    content = SCHEMA_FILE.read_text(encoding="utf-8")
    assert len(content) > 1000, "Schema file is suspiciously small"


def test_all_13_application_tables_in_schema():
    """Verify that all 13 application tables are declared in the DDL."""
    content = SCHEMA_FILE.read_text(encoding="utf-8")
    expected_tables = [
        "satellite_data_sources",
        "satellite_frames",
        "ocean_buoy_telemetry",
        "cyclone_events",
        "inference_logs",
        "disaster_alerts",
        "telemetry_snapshots",
        "advisory_bulletins",
        "ai_models_registry",
        "devices",
        "notification_preferences",
        "vayu_alerts",
        "alert_deliveries",
    ]

    for table in expected_tables:
        pattern = rf"CREATE\s+TABLE\s+IF\s+NOT\s+EXISTS\s+{table}\s*\("
        assert re.search(pattern, content, re.IGNORECASE), f"Table {table} not found in supabase_schema.sql"

    # sqlite_sequence must NOT be in DDL
    assert "sqlite_sequence" not in content.lower()


def test_primary_keys_use_generated_by_default():
    """Verify that all 13 tables use BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY."""
    content = SCHEMA_FILE.read_text(encoding="utf-8")
    matches = re.findall(
        r"id\s+BIGINT\s+GENERATED\s+BY\s+DEFAULT\s+AS\s+IDENTITY\s+PRIMARY\s+KEY",
        content,
        re.IGNORECASE
    )
    assert len(matches) == 13, f"Expected 13 GENERATED BY DEFAULT PKs, found {len(matches)}"

    # Ensure GENERATED ALWAYS is NOT used
    assert "GENERATED ALWAYS" not in content.upper()


def test_foreign_key_constraints_in_schema():
    """Verify required foreign keys exist and prohibited ones are omitted."""
    content = SCHEMA_FILE.read_text(encoding="utf-8")

    # 1. notification_preferences -> devices (CASCADE)
    assert "FOREIGN KEY (device_id) REFERENCES devices(device_id) ON DELETE CASCADE" in content

    # 2. alert_deliveries -> vayu_alerts
    assert "FOREIGN KEY (alert_id) REFERENCES vayu_alerts(alert_id)" in content

    # 3. alert_deliveries -> devices
    assert "FOREIGN KEY (device_id) REFERENCES devices(device_id)" in content

    # Prohibited foreign keys:
    # satellite_frames.source_id -> satellite_data_sources must NOT be an enforced FK
    assert "REFERENCES satellite_data_sources" not in content

    # vayu_alerts.storm_id -> cyclone_events must NOT be an enforced FK
    assert "REFERENCES cyclone_events" not in content


def test_disaster_alerts_schema_includes_all_application_columns():
    """Verify disaster_alerts in PostgreSQL contains the 4 CAP columns missing in SQLite."""
    content = SCHEMA_FILE.read_text(encoding="utf-8")
    
