def test_migration_table_order_respects_dependencies():
    """Verify parent tables precede child tables in MIGRATION_TABLE_ORDER."""
    devices_idx = MIGRATION_TABLE_ORDER.index("devices")
    vayu_alerts_idx = MIGRATION_TABLE_ORDER.index("vayu_alerts")
    notif_prefs_idx = MIGRATION_TABLE_ORDER.index("notification_preferences")
    deliveries_idx = MIGRATION_TABLE_ORDER.index("alert_deliveries")

    assert devices_idx < notif_prefs_idx, "devices must precede notification_preferences"
    assert devices_idx < deliveries_idx, "devices must precede alert_deliveries"
    assert vayu_alerts_idx < deliveries_idx, "vayu_alerts must precede alert_deliveries"
